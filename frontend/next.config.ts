import type { NextConfig } from "next";

// Las llamadas a /api/* se pasan al backend de Spring Boot (en desarrollo y en Vercel).
// Así el navegador ve un solo dominio y la cookie de sesión funciona sin CORS.
const backendUrl = process.env.BACKEND_URL ?? "http://localhost:8080";

const nextConfig: NextConfig = {
  cacheComponents: true,
  partialPrefetching: true,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  // Encabezados de seguridad de todas las páginas. Vercel ya agrega HSTS. Sin Content-Security-Policy por
  // ahora: Next necesita un nonce por pedido para sus scripts en línea (ver docs/decisiones.md, Hito 10).
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
        ],
      },
    ];
  },
  async rewrites() {
    return [
      {
        source: "/api/:path*",
        destination: `${backendUrl}/api/:path*`,
      },
    ];
  },
};

export default nextConfig;
